"""Combined (simultaneous) field-distortion robustness (TDD, red first).

Every prior robustness item isolates ONE axis — additive noise (``robustness``),
nonlinear clipping (``clipping_robustness``), convolutive reverb
(``reverb_robustness``), linear level (``gain_robustness``). Real capture stacks
all of them at once. This composes them in the physical signal-chain order a mic
actually sees — **gain -> reverb -> noise -> clip** — and quantifies the
*compounding gap*: how far simultaneous distortion drops accuracy below what the
single-axis sweeps would predict.

Like its siblings the module under test (``model/combined_distortion.py``) is two
layers: a **pure reduction** (``combined_distortion``) unit-tested with hand-set
numbers, and a heavy ``build_combined_distortion`` that trains one tiny net and
evaluates field-distorted eval sets. Host-only; no device, no AI Hub token.

Red-first contract notes (the module does not exist yet — these tests MUST fail
on the missing import/symbols):
  * Per the design brief the ``CombinedDistortionResult`` / ``ProfilePoint`` /
    ``FieldProfile`` helpers are **methods** (``def clean_accuracy(self)`` …),
    *not* ``@property`` as the siblings happen to use. They are called with ``()``
    throughout this file deliberately.
  * The clip stage replicates ``model/clipping_robustness.py``'s ``_clip_wave``
    (hard-clip to ``clip_ratio*peak`` then rescale back to the original peak), so
    the order test reproduces that exact logic.
  * The build's per-``eval_seed`` eval set is generated by
    ``torch.Generator().manual_seed(eval_seed)`` iterating
    ``for stressed in (False, True): for _ in range(eval_n_per_class)`` via
    ``model.data._synth_waveform`` — the convention the clean-baseline check below
    reproduces.
"""

from __future__ import annotations

import json

import pytest

BAR = 0.8


def _rec(name, gain_db, rt60_s, snr_db, clip_ratio, accuracy, acc_std=None, n=64):
    """Build one (name, gain_db, rt60_s, snr_db, clip_ratio, acc, acc_std, n) record."""
    return (name, gain_db, rt60_s, snr_db, clip_ratio, accuracy, acc_std, n)


# --- injector: apply_field_profile (composes the signal chain) --------------

def test_clean_profile_is_identity_and_draws_no_rng():
    """crit 3a (injector level): a clean/identity profile returns the wave
    bit-for-bit and consumes no RNG, so it reproduces clean features exactly."""
    import torch

    from model.combined_distortion import DEFAULT_PROFILES, apply_field_profile
    from model.data import _synth_waveform

    profiles = {p.name: p for p in DEFAULT_PROFILES}
    wave = _synth_waveform(False, torch.Generator().manual_seed(0))

    gen = torch.Generator().manual_seed(123)
    state_before = gen.get_state()
    out, diag = apply_field_profile(wave, profiles["clean"], gen)
    state_after = gen.get_state()

    assert torch.equal(out, wave)                 # bit-for-bit unchanged
    assert torch.equal(state_before, state_after)  # no RNG draw
    assert diag["tail_fraction"] == 0.0
    assert diag["clipped_fraction"] == 0.0


def test_perturbation_magnitude_is_monotone():
    """Harsher profiles perturb the waveform more: L2 from clean is
    harsh > typical > quiet > clean == 0."""
    import torch

    from model.combined_distortion import DEFAULT_PROFILES, apply_field_profile
    from model.data import _synth_waveform

    profiles = {p.name: p for p in DEFAULT_PROFILES}
    wave = _synth_waveform(False, torch.Generator().manual_seed(0))

    def dist(name):
        gen = torch.Generator().manual_seed(7)
        out, _ = apply_field_profile(wave, profiles[name], gen)
        return float((out - wave).pow(2).sum().sqrt())

    d_clean = dist("clean")
    d_quiet = dist("quiet")
    d_typical = dist("typical")
    d_harsh = dist("harsh")

    assert d_clean == 0.0
    assert d_harsh > d_typical > d_quiet > d_clean


def test_noise_present_iff_snr_set():
    """Noise is added exactly when ``snr_db`` is set. Holding gain fixed and
    flipping only ``snr_db`` isolates the noise stage."""
    import torch

    from model.combined_distortion import FieldProfile, apply_field_profile
    from model.data import _synth_waveform

    wave = _synth_waveform(False, torch.Generator().manual_seed(0))
    factor = 10.0 ** (-6.0 / 20.0)

    prof_gain = FieldProfile("g", -6.0, 0.0, None, 1.0)      # gain only, no noise
    prof_noisy = FieldProfile("gn", -6.0, 0.0, 10.0, 1.0)    # gain + noise

    out_gain, _ = apply_field_profile(wave, prof_gain, torch.Generator().manual_seed(0))
    out_noisy, _ = apply_field_profile(wave, prof_noisy, torch.Generator().manual_seed(0))

    # snr_db is None -> deterministic gain only, no additive noise
    assert torch.allclose(out_gain, wave * factor, atol=1e-6)
    # snr_db set -> noise present, so it differs from the noise-free gain output
    assert not torch.allclose(out_noisy, out_gain, atol=1e-6)


def test_reverb_is_length_preserved():
    """Reverb smears the envelope but keeps the signal length, and reports a
    non-zero reverberant tail."""
    import torch

    from model.combined_distortion import FieldProfile, apply_field_profile
    from model.data import _synth_waveform

    wave = _synth_waveform(False, torch.Generator().manual_seed(0))
