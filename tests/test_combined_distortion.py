def test_negative_gap_anomaly_is_flagged():
    """A profile that scores ABOVE its matched single-axis baseline (negative
    compounding gap) is physically impossible as real robustness — it must be
    surfaced as an anomaly and the verdict must carry the synthetic-eval caveat,
    even when every profile clears the bar (graceful)."""
    from model.combined_distortion import combined_distortion

    records = [
        _rec("clean", 0.0, 0.0, None, 1.0, 0.96),
        _rec("typical", -6.0, 0.3, 10.0, 0.6, 0.90),
        _rec("harsh", -12.0, 0.6, 0.0, 0.35, 0.88),
        _rec("worst_case", -12.0, 1.0, -5.0, 0.25, 0.98),  # beats its baseline
    ]
    single = {"typical": 0.92, "harsh": 0.95, "worst_case": 0.82}
    out = combined_distortion(records, single_axis=single, accuracy_bar=BAR, out_dir=None)

    assert out.graceful() is True                       # every profile clears the bar
    assert out.anomalous_profiles() == ("worst_case",)  # the -0.16 gap profile
    v = out.verdict().lower()
    assert "graceful" in v                              # base verdict preserved
    assert "caveat" in v and "synthetic" in v          # honesty caveat appended
    assert "worst_case" in out.verdict()
    # a clean (no single_axis) result has no anomaly and no caveat
    clean_only = combined_distortion(records, accuracy_bar=BAR, out_dir=None)
    assert clean_only.anomalous_profiles() == ()
    assert "caveat" not in clean_only.verdict().lower()


