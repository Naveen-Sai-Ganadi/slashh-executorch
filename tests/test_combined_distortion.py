def test_build_combined_distortion_end_to_end(tmp_path):
    """crit 3a end-to-end: the clean profile is the identity baseline, so its
    accuracy equals the same model's accuracy on the same undistorted eval set
    EXACTLY. The harsh check is a SOFT, flake-resistant sanity guard (the tiny
    2-epoch model is stochastic — no hard strict inequality)."""
    import torch

    from model.combined_distortion import build_combined_distortion
    from model.data import _synth_waveform
    from model.features import extract
    from model.production import train_production

    out = build_combined_distortion(
        seed=0, epochs=2, n_per_class=16, eval_n_per_class=16,
        eval_seeds=(0,), accuracy_bar=BAR, out_dir=tmp_path,
    )

    assert (tmp_path / "combined_distortion.json").is_file()
    assert (tmp_path / "combined_distortion.md").is_file()

    by = {p.name: p for p in out.points}
    assert "clean" in by and "harsh" in by

    # Separately-computed clean baseline: identical model (train_production is
    # deterministic) on the identically-seeded eval set, NO distortion.
    model, _ = train_production(epochs=2, n_per_class=16, seed=0, threshold=0.8)
    model = model.eval()
    feats, labels = [], []
    for eval_seed in (0,):
        gen = torch.Generator().manual_seed(eval_seed)
        for stressed in (False, True):
            for _ in range(16):
                wave = _synth_waveform(stressed, gen)
                feats.append(extract(wave))     # clean profile == identity
                labels.append(float(stressed))
    x = torch.cat(feats, dim=0)
    y = torch.tensor(labels, dtype=torch.float32).unsqueeze(1)
    with torch.no_grad():
        pred = (model(x).flatten() >= 0.5).float()
    baseline = (pred == y.flatten()).float().mean().item()

    assert by["clean"].accuracy == pytest.approx(baseline, abs=1e-6)
    assert out.clean_accuracy() == pytest.approx(baseline, abs=1e-6)

    # SOFT sanity: simultaneous distortion should not make harsh much better
    # than clean (a gross inversion would signal an order/identity bug).
    assert by["harsh"].accuracy <= by["clean"].accuracy + 0.25
